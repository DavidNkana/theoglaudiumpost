          summary: `This is a summary of the article generated from the source article "${sourceArticle.title}".`,
          slug: `generated-title-from-${sourceArticle.title.toLowerCase().replace(/[^\w\s-]/g, "").replace(/\s+/g, "-").replace(/-+/g, "-")}`,
