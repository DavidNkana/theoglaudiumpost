        </li>
        <li>
          <strong>Clarification:</strong> Language that could reasonably mislead is clarified without changing the core
          facts. We may add a note when the change materially affects reader understanding.
        </li>
        <li>
          <strong>Update:</strong> New information emerges after publication. We add the new details and a timestamp
